/** Offline license list generated by the AboutLibraries Gradle plugin from the resolved dependencies (full texts). */
@Composable
fun LicensesScreen(onBack: () -> Unit) {
  val libraries by produceLibraries(R.raw.aboutlibraries)
  LicenseScaffold(stringResource(R.string.licenses_open), onBack) { modifier ->
    LibrariesContainer(libraries = libraries, modifier = modifier)
  }
}

/** One license text and the components Google lists under it (google_third_party_notices.json, see app/build.gradle.kts). */
@Serializable
data class ThirdPartyNotice(val names: List<String>, val text: String)

/** The licenses of the components bundled inside Google ML Kit, as shipped in its AARs (third_party_licenses). */
@Composable
fun GoogleNoticesScreen(onBack: () -> Unit) {
  val context = LocalContext.current
  val notices by produceState(emptyList<ThirdPartyNotice>()) {
    value = withContext(Dispatchers.IO) {
      runSafely {
        context.assets.open("google_third_party_notices.json").bufferedReader().use { r ->
          AppJson.decodeFromString<List<ThirdPartyNotice>>(r.readText())
        }
      }.getOrDefault(emptyList())
    }
  }
  LicenseScaffold(stringResource(R.string.licenses_google), onBack) { modifier ->
    LazyColumn(modifier) {
      item {
        Text(
          stringResource(R.string.licenses_google_intro),
          style = MaterialTheme.typography.bodyMedium,
          modifier = Modifier.padding(16.dp),
        )
      }
      items(notices, key = { it.names.first() }) { notice -> NoticeItem(notice) }
    }
  }
}

@Composable
private fun NoticeItem(notice: ThirdPartyNotice) {
  var open by remember { mutableStateOf(false) }
  Column(
    Modifier
      .fillMaxWidth()
      .clickable { open = !open }
      .padding(horizontal = 16.dp, vertical = 12.dp),
  ) {
    Text(notice.names.joinToString(", "), style = MaterialTheme.typography.titleSmall)
    if (open) {
      SelectionContainer {
        Text(notice.text, style = MaterialTheme.typography.bodySmall, modifier = Modifier.padding(top = 8.dp))
      }
    }
  }
  HorizontalDivider()
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun LicenseScaffold(title: String, onBack: () -> Unit, content: @Composable (Modifier) -> Unit) {
  Scaffold(
    topBar = {
      TopAppBar(
        title = { Text(title) },
        navigationIcon = {
          IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Filled.ArrowBack, stringResource(R.string.back)) }
        },
      )
    },
  ) { pad -> content(Modifier.fillMaxSize().padding(pad)) }
}
