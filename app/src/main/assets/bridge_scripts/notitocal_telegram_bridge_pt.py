async def init_client(api_id, api_hash):
    global client
    if client is not None and client.is_connected():
        return client
    save_bridge_config(api_id, api_hash)
    client = TelegramClient(SESSION_FILE, int(api_id), str(api_hash), loop=loop)
    await client.connect()
    return client


class BridgeRequestHandler(BaseHTTPRequestHandler):
    def _send_json(self, status, obj):
        body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _host_ok(self):
        host = self.headers.get("Host", "").strip().lower()
        if host.startswith("["):
            name = host.split("]")[0] + "]"
        else:
            name = host.rsplit(":", 1)[0] if ":" in host else host
        if name in LOCAL_HOSTS:
            return True
        # In LAN mode the app connects by IP address (or a .local name); plain domain names are never expected.
        return LAN_MODE and (bool(IP_HOST.match(name)) or name.endswith(".local"))

    def _check_request(self):
        if not self._host_ok():
            self._send_json(403, {"ok": False, "error": "FORBIDDEN_HOST", "detail": M["HOST_REJECTED"]})
            return False
        if self.headers.get("Origin"):
            # The app never sends an Origin header; browsers always do for cross-site requests.
            self._send_json(403, {"ok": False, "error": "FORBIDDEN_ORIGIN", "detail": M["HOST_REJECTED"]})
            return False
        auth_header = self.headers.get("Authorization", "").strip()
        if not auth_header.startswith("Bearer "):
            self._send_json(401, {"ok": False, "error": "UNAUTHORIZED", "detail": M["INVALID_TOKEN"]})
            return False
        if not hmac.compare_digest(auth_header[7:].strip().encode("utf-8"), BRIDGE_TOKEN.encode("utf-8")):
            self._send_json(401, {"ok": False, "error": "UNAUTHORIZED", "detail": M["INVALID_TOKEN"]})
            return False
        return True

    def log_message(self, fmt, *args):
        # Default logging prints full request lines; keep the console free of chat ids and query values.
        sys.stderr.write("%s %s\n" % (self.command, urlparse(self.path).path))

    def do_GET(self):
        if not self._check_request():
            return
        parsed = urlparse(self.path)
        path = parsed.path
        query = parse_qs(parsed.query)
        if path in ("/", "/status", "/health"):
            self.handle_status()
        elif path == "/dialogs":
            self.handle_dialogs()
        elif path == "/allowlist":
            self._send_json(200, {"ok": True, "allowlist": get_allowlist()})
        elif path == "/messages":
            self.handle_messages(query)
        else:
            self._send_json(404, {"ok": False, "error": M["PATH_NOT_FOUND"].format(path=path)})

    def do_POST(self):
        if not self._check_request():
            return
        path = urlparse(self.path).path
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            length = -1
        if length < 0 or length > MAX_BODY_BYTES:
            self._send_json(400, {"ok": False, "error": M["BAD_REQUEST"]})
            return
        body_bytes = self.rfile.read(length) if length > 0 else b"{}"
        try:
            body = json.loads(body_bytes.decode("utf-8"))
        except Exception:
            body = None
        if not isinstance(body, dict):
            self._send_json(400, {"ok": False, "error": M["BAD_REQUEST"]})
            return
        if path == "/auth/sendCode":
            self.handle_send_code(body)
        elif path == "/auth/signIn":
            self.handle_sign_in(body)
        elif path == "/allowlist":
            self.handle_save_allowlist(body)
        else:
            self._send_json(404, {"ok": False, "error": M["PATH_NOT_FOUND"].format(path=path)})

    def _run(self, coro, timeout):
        return asyncio.run_coroutine_threadsafe(coro, loop).result(timeout=timeout)

    def handle_status(self):
        async def check():
            global client
            if client is None:
                cfg = load_bridge_config()
                if cfg.get("api_id") and cfg.get("api_hash"):
                    try:
                        client = await init_client(cfg["api_id"], cfg["api_hash"])
                    except Exception as ex:
                        print(f"Status auto-init error: {ex}")
            if client is None:
                return {"ok": True, "authorized": False, "detail": M["NO_CLIENT"], "allowlist_count": len(get_allowlist()), "token_required": True}
            if await client.is_user_authorized():
                me = await client.get_me()
                user_name = f"{me.first_name or ''} {me.last_name or ''}".strip() or me.username or "Telegram"
                return {"ok": True, "authorized": True, "user": user_name, "allowlist_count": len(get_allowlist()), "token_required": True}
            return {"ok": True, "authorized": False, "detail": M["NOT_LOGGED_CODE"], "token_required": True}

        try:
            self._send_json(200, self._run(check(), 10))
        except Exception as e:
            self._send_json(200, {"ok": True, "authorized": False, "detail": f"Status: {e}", "token_required": True})

    def handle_send_code(self, body):
        api_id = str(body.get("api_id", "")).strip()
        api_hash = str(body.get("api_hash", "")).strip()
        phone = str(body.get("phone", "")).strip()
        if not api_id.isdigit() or not api_hash or not phone:
            self._send_json(400, {"ok": False, "error": M["SENDCODE_REQ"]})
            return

        async def send():
            c = await init_client(api_id, api_hash)
            req = await c.send_code_request(phone)
            current_phone_code_hash[phone] = req.phone_code_hash
            save_bridge_config(api_id, api_hash, phone)
            save_pending_auth(phone, req.phone_code_hash)
            return {"ok": True, "phone_code_hash": req.phone_code_hash, "detail": M["CODE_SENT"].format(phone=phone)}

        try:
            self._send_json(200, self._run(send(), 15))
        except Exception as e:
            self._send_json(500, {"ok": False, "error": str(e)})

    def handle_sign_in(self, body):
        phone = str(body.get("phone", "")).strip()
        code = str(body.get("code", "")).strip()
        pending = load_pending_auth()
        phone_code_hash = (
            body.get("phone_code_hash")
            or current_phone_code_hash.get(phone)
            or (pending.get("phone_code_hash") if pending.get("phone") == phone else None)
        )
        password = str(body.get("password", "")).strip()
        if not phone or not code:
            self._send_json(400, {"ok": False, "error": M["SIGNIN_REQ"]})
            return

        async def sign():
            global client
            if client is None:
                cfg = load_bridge_config()
                if cfg.get("api_id") and cfg.get("api_hash"):
                    client = await init_client(cfg["api_id"], cfg["api_hash"])
                else:
                    raise Exception(M["CLIENT_NOT_INIT"])
            try:
                user = await client.sign_in(phone=phone, code=code, phone_code_hash=phone_code_hash)
            except errors.SessionPasswordNeededError:
                if not password:
                    return {"ok": False, "error": "2FA_NEEDED", "detail": M["TWOFA"]}
                user = await client.sign_in(password=password)
            try:
                await client(UpdateStatusRequest(offline=True))
            except Exception:
                pass
            if os.path.exists(AUTH_FILE):
                try:
                    os.remove(AUTH_FILE)
                except Exception:
                    pass
            return {"ok": True, "user": getattr(user, "first_name", "") or "Telegram", "detail": M["LOGGED_IN"]}

        try:
            res = self._run(sign(), 20)
            self._send_json(200 if res.get("ok") else 409, res)
        except Exception as e:
            self._send_json(500, {"ok": False, "error": str(e)})

    def handle_dialogs(self):
        async def fetch():
            if client is None or not (await client.is_user_authorized()):
                dialogs = [{"id": cid, "title": name, "username": "", "type": "group" if cid.startswith("-") else "person"}
                           for cid, name in get_allowlist().items()]
                return {"ok": True, "dialogs": dialogs, "source": "allowlist_fallback"}
            results = []
            async for dialog in client.iter_dialogs(limit=250):
                ent = dialog.entity
                d_type = "group"
                if isinstance(ent, Channel):
                    d_type = "channel" if ent.broadcast else "group"
                elif isinstance(ent, Chat):
                    d_type = "group"
                elif isinstance(ent, User):
                    d_type = "person"
                results.append({
                    "id": str(dialog.id),
                    "title": dialog.name or "-",
                    "username": getattr(ent, "username", "") or "",
                    "type": d_type,
                    "unread_count": dialog.unread_count,
                })
            return {"ok": True, "dialogs": results, "source": "telegram_mtproto"}

        try:
            self._send_json(200, self._run(fetch(), 25))
        except Exception as e:
            self._send_json(500, {"ok": False, "error": str(e)})

    def handle_save_allowlist(self, body):
        if not all(re.fullmatch(r"-?\d{1,20}", str(k)) and isinstance(v, str) and len(v) <= 200 for k, v in body.items()) or len(body) > 2000:
            self._send_json(400, {"ok": False, "error": M["ALLOWLIST_INVALID"]})
            return
        try:
            tmp = ALLOWLIST_FILE + ".tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                json.dump(body, f, indent=2, ensure_ascii=False)
            os.replace(tmp, ALLOWLIST_FILE)
            self._send_json(200, {"ok": True, "saved": len(body)})
        except Exception as e:
            self._send_json(500, {"ok": False, "error": str(e)})

    def handle_messages(self, query):
        since_raw = query.get("since", ["0"])[0]
        chat_since = {}
        global_since = 0
        if ":" in since_raw:
            for part in since_raw.split(","):
                if ":" in part:
                    p_chat, p_id = part.strip().split(":", 1)
                    try:
                        chat_since[p_chat] = int(p_id)
                    except ValueError:
                        pass
        else:
            try:
                global_since = int(since_raw)
            except ValueError:
                global_since = 0
        try:
            limit = max(1, min(int(query.get("limit", ["20"])[0]), 50))
        except ValueError:
            limit = 20

        async def fetch():
            if client is None or not (await client.is_user_authorized()):
                return {"ok": False, "error": M["NOT_LOGGED"], "messages": []}
            messages = []
            for chat_id_str, chat_name in get_allowlist().items():
                try:
                    cid = int(chat_id_str)
                    chat_since_id = chat_since.get(str(cid), chat_since.get(chat_id_str, global_since))
                    entity = await client.get_entity(cid)
                    async for msg in client.iter_messages(entity, limit=limit):
                        if chat_since_id > 0 and msg.id <= chat_since_id:
                            break
                        if not msg.message and not msg.photo:
                            continue
                        sender_name = "Telegram"
                        try:
                            sender = await msg.get_sender()
                            if sender:
                                sender_name = f"{getattr(sender, 'first_name', '') or ''} {getattr(sender, 'last_name', '') or ''}".strip() or getattr(sender, "username", "") or "Telegram"
                        except Exception:
                            pass
                        messages.append({
                            "id": msg.id,
                            "chat_id": str(cid),
                            "chat": chat_name,
                            "sender": sender_name,
                            "text": msg.message or "",
                            "date": int(msg.date.replace(tzinfo=timezone.utc).timestamp()),
                            "is_group": str(cid).startswith("-"),
                            "has_photo": bool(msg.photo),
                        })
                except Exception as ex:
                    print(M["ERR_CHAT"].format(chat_id_str=chat_id_str, ex=ex))
            return {"ok": True, "messages": messages}

        try:
            self._send_json(200, self._run(fetch(), 30))
        except Exception as e:
            self._send_json(500, {"ok": False, "error": str(e), "messages": []})


def main():
    global loop
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    threading.Thread(target=loop.run_forever, daemon=True).start()

    server = ThreadingHTTPServer((HOST, PORT), BridgeRequestHandler)
    server.daemon_threads = True

    cfg = load_bridge_config()
    if cfg.get("api_id") and cfg.get("api_hash"):
        async def auto_start():
            try:
                await init_client(cfg["api_id"], cfg["api_hash"])
                if await client.is_user_authorized():
                    me = await client.get_me()
                    print(f"Telegram user auto-connected: {getattr(me, 'first_name', '') or getattr(me, 'username', 'user')}")
            except Exception as e:
                print(f"Auto-connect note: {e}")
        asyncio.run_coroutine_threadsafe(auto_start(), loop)
    print("=" * 65)
    print(M["RUNNING"].format(HOST=HOST, PORT=PORT))
    print(M["MODE_LAN"] if LAN_MODE else M["MODE_LOCAL"])
    if LAN_MODE:
        print(M["CONSOLE_LAN_WARN"])
    print("-" * 65)
    print(M["CONSOLE_TOKEN"])
    print(BRIDGE_TOKEN)
    print("=" * 65)
    print(M["PRESS_CTRL_C"])
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n" + M["STOPPING"])
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
